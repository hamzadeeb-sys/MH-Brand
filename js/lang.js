const I18n = {
  currentLang: localStorage.getItem('mh_lang') || 'ar',

  init() {
    this.setLanguage(this.currentLang);

    // ربط أزرار التبديل في الـ Header
    document.querySelectorAll('.lang-toggle-btn').forEach(btn => {
      btn.addEventListener('click', () => {
        const nextLang = this.currentLang === 'ar' ? 'en' : 'ar';
        this.setLanguage(nextLang);
      });
    });
  },

  setLanguage(lang) {
    this.currentLang = lang;
    localStorage.setItem('mh_lang', lang);

    // تعديل اتجاه المستند واللغة في <html>
    document.documentElement.lang = lang;
    document.documentElement.dir = lang === 'ar' ? 'rtl' : 'ltr';
    document.body.setAttribute('data-lang', lang);

    // تطبيق كل النصوص المعرفة بـ data-i18n
    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.getAttribute('data-i18n');
      if (translations[lang] && translations[lang][key]) {
        el.innerText = translations[lang][key];
      }
    });

    // تحديث نص زر التبديل
    document.querySelectorAll('.lang-toggle-btn').forEach(btn => {
      btn.innerText = translations[lang].lang_btn;
    });
  }
};

document.addEventListener('DOMContentLoaded', () => I18n.init());
